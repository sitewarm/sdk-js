// Regenerates src/generated/* from the vendored spec (openapi/openapi.yaml).
//   - schema.d.ts   : types from openapi-typescript
//   - operations.ts : operationId -> method/path table used by the runtime client
// CI runs this and fails on drift (diff of src/generated).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";
import { parse } from "yaml";

const specUrl = new URL("../openapi/openapi.yaml", import.meta.url);
const outDir = new URL("../src/generated/", import.meta.url);
const banner = "// GENERATED by scripts/generate.mjs from openapi/openapi.yaml. Do not edit.\n";

const ast = await openapiTS(specUrl);
writeFileSync(new URL("schema.d.ts", outDir), banner + astToString(ast));

const spec = parse(readFileSync(fileURLToPath(specUrl), "utf8"));
const methods = ["get", "put", "post", "patch", "delete"];
const rows = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const method of methods) {
    const op = item[method];
    if (!op) continue;
    const params = [...(item.parameters ?? []), ...(op.parameters ?? [])];
    const idem = params
      .map((p) => p.$ref ?? "")
      .find((r) => r.endsWith("/IdempotencyKey") || r.endsWith("/IdempotencyKeyRequired"));
    const idempotency = !idem ? "none" : idem.endsWith("Required") ? "required" : "optional";
    rows.push(
      `  ${op.operationId}: { method: "${method.toUpperCase()}", path: "${path}", idempotency: "${idempotency}" },`,
    );
  }
}
writeFileSync(
  new URL("operations.ts", outDir),
  `${banner}export type IdempotencySupport = "none" | "optional" | "required";\n\n` +
    `export const operationTable = {\n${rows.join("\n")}\n} as const satisfies Record<\n  string,\n  { method: string; path: string; idempotency: IdempotencySupport }\n>;\n`,
);
console.log(`generated ${rows.length} operations`);
